    @Test
    fun matchesReferenceSgp4() {
        var worst = 0.0
        for (c in cases) {
            val o = OrbitElements("TEST", 1, epochMs, c.n, c.e, c.i, c.raan, c.argp, c.m, if (c.name == "LEO") 3e-4 else 0.0)
            val p = o.inertial(epochMs + c.hours * 3_600_000L)
            val err = (p - Vec3(c.x, c.y, c.z)).norm()
            println("${c.name} +${c.hours}h error = %.6f km".format(err))
            worst = maxOf(worst, err)
        }
        println("worst = %.2f km".format(worst))
        assertTrue("propagator deviates $worst km from SGP4", worst < 1e-3)
    }

    @Test
    fun geodeticRoundTrip() {
        val p = Geo.geodeticToEcef(12.97, 77.59, 0.92)
        val (lat, lon, alt) = Geo.ecefToGeodetic(p)
        assertEquals(12.97, lat, 1e-9)
        assertEquals(77.59, lon, 1e-9)
        assertEquals(0.92, alt, 1e-6)
    }

    @Test
    fun shellRangeMatchesAzElOfPoint() {
        val lat = 40.0; val lon = -105.0
        val user = Geo.geodeticToEcef(lat, lon, 1.6)
        val dir = Geo.enuDirection(lat, lon, 133.0, 37.0)
        val d = Geo.rangeToShell(user, dir, 26_560.0)
        val sat = user + dir * d
        assertEquals(26_560.0, sat.norm(), 1e-6)
        val (az, el) = Geo.azEl(lat, lon, user, sat)
        assertEquals(133.0, az, 1e-9)
        assertEquals(37.0, el, 1e-9)
    }

    @Test
    fun parsesPrnFromNames() {
        assertEquals(13, OrbitElements.parsePrn("GPS BIIR-2  (PRN 13)", Constellation.GPS))
        assertEquals(11, OrbitElements.parsePrn("GSAT0101 (PRN E11)", Constellation.GALILEO))
        assertEquals(19, OrbitElements.parsePrn("BEIDOU-3 M1 (C19)", Constellation.BEIDOU))
    }
